let order = 0;
function P(o) {
  order += 1;
  const options = o.options;
  return {
    id: `prod-${String(order).padStart(3, '0')}`,
    slug: o.slug,
    name: o.name,
    categoryId: o.categoryId,
    shortDescription: o.short,
    description: o.description,
    features: o.features,
    images: o.images,
    tags: o.tags || [],
    options,
    printMethods: o.printMethods,
    moq: o.moq,
    basePrice: o.price,
    tiers: tiersFrom(o.price, o.moq),
    inventory: buildInventory(options, [], o.stock ?? 400).map((r, i) => ({ ...r, stock: i % 11 === 7 ? 0 : (o.stock ?? 400) - ((i * 37) % 180) })),
    lowStockThreshold: 120,
    leadTimeDays: o.lead ?? 7,
    featured: !!o.featured,
    bestSeller: !!o.best,
    status: 'published',
    rating: 0,
    reviewCount: 0,
    createdAt: new Date(Date.now() - (60 - order) * 86400000).toISOString(),
  };
}

